// Writes examples/__index__.ts: a lazy loader for every example file, so a
// docs page can render `<ComponentPreview name="button-demo" />` by name.

import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "examples");
const out = path.join(dir, "__index__.ts");

const names = (await readdir(dir))
  .filter((file) => file.endsWith(".tsx"))
  .map((file) => file.slice(0, -".tsx".length))
  .sort();

const entries = names
  .map((name) => `  "${name}": () => import("./${name}"),`)
  .join("\n");

const contents = `// Generated by scripts/build-examples.mjs; don't edit.
import type { ComponentType } from "react";

export const examples: Record<
  string,
  () => Promise<{ default: ComponentType }>
> = {
${entries}
};
`;

const previous = await readFile(out, "utf8").catch(() => "");
if (previous !== contents) {
  await writeFile(out, contents);
}
console.log(`examples: indexed ${names.length} files`);
